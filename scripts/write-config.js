// Writes public/config.js from .env, so every key (Google, GitHub, TURN)
// lives in one file. The browser can't read .env, and Bonezegei only
// serves files, so config.js is generated instead of read at runtime.
const fs = require("node:fs");
const path = require("node:path");

const OUT_FILE = path.join(__dirname, "..", "public", "config.js");

const isSet = (value) => !!value && !value.startsWith("YOUR_");

// Turns .env values into the object the page reads as window.JMEET_CONFIG
function buildConfig(env) {
    const googleClientId = isSet(env.GOOGLE_CLIENT_ID) ? env.GOOGLE_CLIENT_ID : "";
    // Relative, so the button stays on whichever address the page was opened on
    const githubAuthUrl = isSet(env.GITHUB_CLIENT_ID) ? "/auth/github" : "";
    if (!googleClientId && !githubAuthUrl) {
        throw new Error("Set GOOGLE_CLIENT_ID or the GitHub keys in .env (see .env.example). config.js was not changed.");
    }

    const turnUrls = isSet(env.TURN_URLS)
        ? env.TURN_URLS.split(",").map((url) => url.trim()).filter(Boolean)
        : [];
    if (turnUrls.length && !(isSet(env.TURN_USERNAME) && isSet(env.TURN_CREDENTIAL))) {
        throw new Error("TURN_URLS is set, so TURN_USERNAME and TURN_CREDENTIAL are needed too.");
    }
    const iceServers = turnUrls.length
        ? [{ urls: turnUrls, username: env.TURN_USERNAME, credential: env.TURN_CREDENTIAL }]
        : [];

    return { googleClientId, githubAuthUrl, iceServers };
}

function renderConfigJs(config) {
    return "// Generated by npm run config from .env. Edit .env, not this file.\n"
        + `window.JMEET_CONFIG = ${JSON.stringify(config, null, 4)};\n`;
}

// Writes config.js and returns a summary like "Google, GitHub"; throws when
// .env has no sign-in provider, leaving the old file alone
function writeConfigFile(env) {
    const config = buildConfig(env);
    fs.writeFileSync(OUT_FILE, renderConfigJs(config));
    return [
        config.googleClientId && "Google",
        config.githubAuthUrl && "GitHub",
        config.iceServers.length && "TURN"
    ].filter(Boolean).join(", ");
}

function main() {
    try {
        console.log(`Wrote public/config.js (${writeConfigFile(process.env)})`);
    } catch (err) {
        console.error(err.message);
        process.exit(1);
    }
}

if (require.main === module) main();

module.exports = { buildConfig, renderConfigJs, writeConfigFile };
